SELECT
    n.SALES_DATE,
    n.PRODUCT_ID,
    n.USER_ID,
    n.SALES_AMOUNT
FROM ONLINE_SALE n
WHERE YEAR(n.SALES_DATE) = 2022
  AND MONTH(n.SALES_DATE) = 3

UNION ALL

SELECT
    f.SALES_DATE,
    f.PRODUCT_ID,
    NULL AS USER_ID,
    f.SALES_AMOUNT
FROM OFFLINE_SALE f
WHERE YEAR(f.SALES_DATE) = 2022
  AND MONTH(f.SALES_DATE) = 3

ORDER BY SALES_DATE, PRODUCT_ID, USER_ID;
